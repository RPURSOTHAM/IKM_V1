def is_allowed_metric(metric_name: str) -> bool:
    return metric_name in ALLOWED_METRIC_NAMES


def benchmark_catalog() -> list[dict[str, Any]]:
    return [dict(row) for row in BENCHMARK_METRICS]


def benchmark_summary() -> dict[str, Any]:
    collecting = sum(1 for m in BENCHMARK_METRICS if m["status"] == "collecting")
    derived = sum(1 for m in BENCHMARK_METRICS if m["status"] == "derived")
    planned = sum(1 for m in BENCHMARK_METRICS if m["status"] == "planned")
    return {
        "total": len(BENCHMARK_METRICS),
        "collecting": collecting,
        "derived": derived,
        "planned": planned,
        "allowed_storage_metrics": sorted(ALLOWED_METRIC_NAMES),
    }
